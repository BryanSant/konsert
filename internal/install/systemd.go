package install

import (
	"context"
	"fmt"
	"path/filepath"
	"strconv"
	"strings"
)

// systemdBackend installs a systemd user unit, so the daemon runs as the user (with the
// user's agent CLI logins) and, with lingering, keeps running while logged out.
type systemdBackend struct{}

// SystemdUnit is the unit file name of an instance.
func SystemdUnit(instance string) string { return unitBase(instance) + ".service" }

func (systemdBackend) unitPath(in *Installer, instance string) string {
	return filepath.Join(in.Env.UnitDir, SystemdUnit(instance))
}

// systemdQuote quotes one ExecStart word: double quotes, with backslash and quote
// escaped, "%" doubled (specifiers) and "$" doubled (variable expansion).
func systemdQuote(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "%", "%%", "$", "$$")
	return `"` + r.Replace(s) + `"`
}

// RenderUnit renders the systemd user unit.
func RenderUnit(description string, argv []string, env map[string]string, workDir string) []byte {
	words := make([]string, len(argv))
	for i, a := range argv {
		words[i] = systemdQuote(a)
	}
	var b strings.Builder
	b.WriteString("# Generated by `konsertd install`; remove with `konsertd uninstall`.\n")
	b.WriteString("[Unit]\n")
	b.WriteString("Description=" + description + "\n")
	b.WriteString("Documentation=https://github.com/BryanSant/konsert/blob/main/docs/deploy.md\n")
	b.WriteString("StartLimitIntervalSec=0\n\n")
	b.WriteString("[Service]\n")
	b.WriteString("Type=simple\n")
	if workDir != "" {
		b.WriteString("WorkingDirectory=" + strings.ReplaceAll(workDir, "%", "%%") + "\n")
	}
	for _, k := range sortedKeys(env) {
		b.WriteString("Environment=" + systemdQuote(k+"="+env[k]) + "\n")
	}
	b.WriteString("ExecStart=" + strings.Join(words, " ") + "\n")
	b.WriteString("Restart=always\n")
	b.WriteString("RestartSec=5\n")
	// SIGTERM to konsertd only, so it can stop its agent sessions itself; anything left
	// after the timeout is killed.
	b.WriteString("KillMode=mixed\n")
	b.WriteString("TimeoutStopSec=30\n\n")
	b.WriteString("[Install]\n")
	b.WriteString("WantedBy=default.target\n")
	return []byte(b.String())
}

func (s systemdBackend) render(in *Installer, spec Spec) (string, []byte, error) {
	argv := append([]string{spec.Exe}, runArgs(in.ConfigPath(spec.Instance), spec.ExtraArgs, "")...)
	env := map[string]string{}
	if in.Env.PATH != "" {
		env["PATH"] = in.Env.PATH
	}
	desc := "Konsert worker daemon"
	if spec.Instance != "" {
		desc += " (" + spec.Instance + ")"
	}
	return s.unitPath(in, spec.Instance), RenderUnit(desc, argv, env, in.Env.Home), nil
}

// checkUserManager fails clearly when there is no systemd user instance to talk to
// (containers, su sessions without XDG_RUNTIME_DIR, non-systemd distros).
func (systemdBackend) checkUserManager(ctx context.Context, in *Installer) error {
	if _, err := in.Runner.Run(ctx, "", "systemctl", "--user", "show-environment"); err != nil {
		return fmt.Errorf("no systemd user instance is reachable (%v).\n"+
			"konsertd install needs `systemctl --user`: run it from a normal login session of the user "+
			"the daemon should run as (not a container, and not `su` without XDG_RUNTIME_DIR). "+
			"In containers, use the Quadlet or a supervisor instead (docs/deploy.md)", err)
	}
	return nil
}

func (s systemdBackend) install(ctx context.Context, in *Installer, spec Spec) error {
	if err := s.checkUserManager(ctx, in); err != nil {
		return err
	}
	path, content, err := s.render(in, spec)
	if err != nil {
		return err
	}
	if err := writeFile(path, content, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	in.printf("Wrote systemd user unit %s\n", path)
	unit := SystemdUnit(spec.Instance)
	if _, err := in.Runner.Run(ctx, "", "systemctl", "--user", "daemon-reload"); err != nil {
		return err
	}
	if spec.NoStart {
		if _, err := in.Runner.Run(ctx, "", "systemctl", "--user", "enable", unit); err != nil {
			return err
		}
		in.printf("Enabled %s (not started: --no-start)\n", unit)
	} else {
		// restart (not just start) so a reinstall picks up the new config.
		if _, err := in.Runner.Run(ctx, "", "systemctl", "--user", "enable", unit); err != nil {
			return err
		}
		if _, err := in.Runner.Run(ctx, "", "systemctl", "--user", "restart", unit); err != nil {
			return err
		}
		in.printf("Enabled and started %s; logs: journalctl --user -u %s -f\n", unit, unit)
	}
	if !spec.NoLinger {
		s.enableLinger(ctx, in)
	}
	return nil
}

// enableLinger keeps the user manager (and so konsertd) running while the user is
// logged out. It needs polkit's set-self-linger permission, which most desktops grant;
// otherwise the command to run is printed.
func (systemdBackend) enableLinger(ctx context.Context, in *Installer) {
	user := in.Env.User
	if user == "" {
		return
	}
	out, err := in.Runner.Run(ctx, "", "loginctl", "show-user", user, "--property=Linger", "--value")
	if err == nil && strings.TrimSpace(out) == "yes" {
		in.printf("Lingering is already enabled for %s.\n", user)
		return
	}
	if _, err := in.Runner.Run(ctx, "", "loginctl", "enable-linger", user); err != nil {
		in.printf("Could not enable lingering (%v).\nTo keep konsertd running while you are logged out, run:\n  sudo loginctl enable-linger %s\n", err, user)
		return
	}
	in.printf("Enabled lingering for %s so konsertd keeps running while you are logged out.\n", user)
}

func (s systemdBackend) uninstall(ctx context.Context, in *Installer, instance string) error {
	unit := SystemdUnit(instance)
	path := s.unitPath(in, instance)
	if err := s.checkUserManager(ctx, in); err != nil {
		if fileExists(path) {
			return err
		}
	} else {
		if _, err := in.Runner.Run(ctx, "", "systemctl", "--user", "disable", "--now", unit); err == nil {
			in.printf("Stopped and disabled %s\n", unit)
		}
	}
	removed, err := removeFile(path)
	if err != nil {
		return fmt.Errorf("remove %s: %w", path, err)
	}
	if removed {
		in.printf("Removed %s\n", path)
		_, _ = in.Runner.Run(ctx, "", "systemctl", "--user", "daemon-reload")
		_, _ = in.Runner.Run(ctx, "", "systemctl", "--user", "reset-failed", unit)
	} else {
		in.printf("No unit at %s\n", path)
	}
	in.printf("Lingering (if enabled) was left as is; disable it with `loginctl disable-linger` if nothing else needs it.\n")
	return nil
}

func (s systemdBackend) status(ctx context.Context, in *Installer, instance string) (Status, error) {
	unit := SystemdUnit(instance)
	st := Status{
		Mechanism:      "systemd user unit",
		Name:           unit,
		DefinitionPath: s.unitPath(in, instance),
		ConfigPath:     in.ConfigPath(instance),
		LogPath:        "journalctl --user -u " + unit,
	}
	st.Installed = fileExists(st.DefinitionPath)
	if !st.Installed {
		return st, nil
	}
	if err := s.checkUserManager(ctx, in); err != nil {
		return st, err
	}
	out, _ := in.Runner.Run(ctx, "", "systemctl", "--user", "show", unit,
		"--property=ActiveState,SubState,MainPID,UnitFileState")
	props := map[string]string{}
	for _, line := range strings.Split(out, "\n") {
		if k, v, ok := strings.Cut(strings.TrimSpace(line), "="); ok {
			props[k] = v
		}
	}
	st.Running = props["ActiveState"] == "active"
	st.PID, _ = strconv.Atoi(props["MainPID"])
	st.Detail = fmt.Sprintf("%s (%s), %s", props["ActiveState"], props["SubState"], props["UnitFileState"])
	return st, nil
}
